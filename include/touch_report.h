// Two parallel contacts, six bytes per contact, then one Contact Count byte.
// BLE Report Reference carries ID 1; do not prepend a report ID to the payload.
#define TOUCH_FINGER_DESCRIPTOR \
  0x09, 0x22, 0xA1, 0x02, \
  0x09, 0x42, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02, \
  0x75, 0x07, 0x95, 0x01, 0x81, 0x03, \
  0x09, 0x51, 0x15, 0x00, 0x25, 0x01, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02, \
  0x05, 0x01, 0x09, 0x30, 0x09, 0x31, \
  0x15, 0x00, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, \
  0x05, 0x0D, 0xC0

static const uint8_t TOUCH_REPORT_MAP[] = {
  0x05, 0x0D, 0x09, 0x04, 0xA1, 0x01, 0x85, 0x01,
  TOUCH_FINGER_DESCRIPTOR,
  TOUCH_FINGER_DESCRIPTOR,
  0x09, 0x54, 0x15, 0x00, 0x25, 0x02,
  0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
  0x85, 0x02, 0x09, 0x55, 0x15, 0x00, 0x25, 0x02,
  0x75, 0x08, 0x95, 0x01, 0xB1, 0x02,
  0xC0
};
#undef TOUCH_FINGER_DESCRIPTOR

struct TouchPoint {
  bool down = false;
  uint16_t x = 500;
  uint16_t y = 500;
};

inline void encodeTouchReport(const TouchPoint points[2], uint8_t report[13]) {
  for (unsigned i = 0; i < 2; ++i) {
    const uint16_t x = uint32_t(points[i].x) * 32767 / 1000;
    const uint16_t y = uint32_t(points[i].y) * 32767 / 1000;
    report[i * 6] = points[i].down ? 1 : 0;
    report[i * 6 + 1] = i;
    report[i * 6 + 2] = x & 255;
    report[i * 6 + 3] = x >> 8;
    report[i * 6 + 4] = y & 255;
    report[i * 6 + 5] = y >> 8;
  }
  // Both slots are present in every frame, including explicit lift reports.
  report[12] = 2;
}
